package xmath

type decimal struct {
	d     [800]byte // 数字，大端表示
	nd    int       // 已使用的数字位数
	dp    int       // 小数点位置
	neg   bool      // 负数标记
	trunc bool      // 超出 d[:nd] 而被丢弃的非零数字
}

func (a *decimal) String() string {
	n := 10 + a.nd
	if a.dp > 0 {
		n += a.dp
	}
	if a.dp < 0 {
		n += -a.dp
	}

	buf := make([]byte, n)
	w := 0
	switch {
	case a.nd == 0:
		return "0"

	case a.dp <= 0:
		// 用 0 填充小数点与数字之间的空隙
		buf[w] = '0'
		w++
		buf[w] = '.'
		w++
		w += digitZero(buf[w : w+-a.dp])
		w += copy(buf[w:], a.d[0:a.nd])

	case a.dp < a.nd:
		// 小数点位于数字中间
		w += copy(buf[w:], a.d[0:a.dp])
		buf[w] = '.'
		w++
		w += copy(buf[w:], a.d[a.dp:a.nd])

	default:
		// 用 0 填充数字与小数点之间的空隙
		w += copy(buf[w:], a.d[0:a.nd])
		w += digitZero(buf[w : w+a.dp-a.nd])
	}
	return string(buf[0:w])
}

func digitZero(dst []byte) int {
	for i := range dst {
		dst[i] = '0'
	}
	return len(dst)
}

// 去掉数字末尾的 0。
// （末尾的 0 没有意义；小数点的位置是独立于数字位数单独记录的。）
func trim(a *decimal) {
	for a.nd > 0 && a.d[a.nd-1] == '0' {
		a.nd--
	}
	if a.nd == 0 {
		a.dp = 0
	}
}

// 将 v 赋值给 a。
func (a *decimal) Assign(v uint64) {
	var buf [24]byte

	// 将十进制数字逆序写入 buf。
	n := 0
	for v > 0 {
		v1 := v / 10
		v -= 10 * v1
		buf[n] = byte(v + '0')
		n++
		v = v1
	}

	// 再次反转，得到正向的十进制数字存入 a.d。
	a.nd = 0
	for n--; n >= 0; n-- {
		a.d[a.nd] = buf[n]
		a.nd++
	}
	a.dp = a.nd
	trim(a)
}

// 单次操作中不会发生溢出的最大移位位数。
// uint 为 32 位或 64 位，必须能容纳 9<<k。
const (
	uintSize = 32 << (^uint(0) >> 63)
	maxShift = uintSize - 4
)

// 按 k 位进行二进制右移（即除以 2）。为避免溢出，要求 k <= maxShift。
func rightShift(a *decimal, k uint) {
	r := 0 // 读指针
	w := 0 // 写指针

	// 先取出足以完成首次移位的前导数字。
	var n uint
	for ; n>>k == 0; r++ {
		if r >= a.nd {
			if n == 0 {
				// a == 0；正常情况下到不了这里，但仍处理一下。
				a.nd = 0
				return
			}
			for n>>k == 0 {
				n = n * 10
				r++
			}
			break
		}
		c := uint(a.d[r])
		n = n*10 + c - '0'
	}
	a.dp -= r - 1

	var mask uint = (1 << k) - 1

	// 读取一位数字，同时写出一位数字。
	for ; r < a.nd; r++ {
		c := uint(a.d[r])
		dig := n >> k
		n &= mask
		a.d[w] = byte(dig + '0')
		w++
		n = n*10 + c - '0'
	}

	// 写出多余的数字。
	for n > 0 {
		dig := n >> k
		n &= mask
		if w < len(a.d) {
			a.d[w] = byte(dig + '0')
			w++
		} else if dig > 0 {
			a.trunc = true
		}
		n = n * 10
	}

	a.nd = w
	trim(a)
}

