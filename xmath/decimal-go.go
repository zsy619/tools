// b 的前缀是否按字典序小于 s？
func prefixIsLessThan(b []byte, s string) bool {
	for i := 0; i < len(s); i++ {
		if i >= len(b) {
			return true
		}
		if b[i] != s[i] {
			return b[i] < s[i]
		}
	}
	return false
}

// 按 k 位进行二进制左移（即乘以 2）。为避免溢出，要求 k <= maxShift。
func leftShift(a *decimal, k uint) {
	delta := leftcheats[k].delta
	if prefixIsLessThan(a.d[0:a.nd], leftcheats[k].cutoff) {
		delta--
	}

	r := a.nd         // 读索引
	w := a.nd + delta // 写索引

	// 读取一位数字，同时写出一位数字。
	var n uint
	for r--; r >= 0; r-- {
		n += (uint(a.d[r]) - '0') << k
		quo := n / 10
		rem := n - 10*quo
		w--
		if w < len(a.d) {
			a.d[w] = byte(rem + '0')
		} else if rem != 0 {
			a.trunc = true
		}
		n = quo
	}

	// 写出多余的数字。
	for n > 0 {
		quo := n / 10
		rem := n - 10*quo
		w--
		if w < len(a.d) {
			a.d[w] = byte(rem + '0')
		} else if rem != 0 {
			a.trunc = true
		}
		n = quo
	}

	a.nd += delta
	if a.nd >= len(a.d) {
		a.nd = len(a.d)
	}
	a.dp += delta
	trim(a)
}

// 按 k 位二进制左移（k > 0）或右移（k < 0）。
func (a *decimal) Shift(k int) {
	switch {
	case a.nd == 0:
		// 无需处理：a == 0
	case k > 0:
		for k > maxShift {
			leftShift(a, maxShift)
			k -= maxShift
		}
		leftShift(a, uint(k))
	case k < 0:
		for k < -maxShift {
			rightShift(a, maxShift)
			k += maxShift
		}
		rightShift(a, uint(-k))
	}
}

// 若将 a 截断到 nd 位，是否应进位？
func shouldRoundUp(a *decimal, nd int) bool {
	if nd < 0 || nd >= a.nd {
		return false
	}
	if a.d[nd] == '5' && nd+1 == a.nd { // 恰好处于中间——四舍五入取偶数（银行家舍入）
		// 若发生过截断，实际值会比记录值略高——总是进位
		if a.trunc {
			return true
		}
		return nd > 0 && (a.d[nd-1]-'0')%2 != 0
	}
	// 并非恰好一半——由下一位数字决定
	return a.d[nd] >= '5'
}

// 将 a 四舍五入到 nd 位（或更少位）。
// 若 nd 为 0，表示在小数点左侧一位处进行舍入，
// 例如 0.09 -> 0.1。
func (a *decimal) Round(nd int) {
	if nd < 0 || nd >= a.nd {
		return
	}
	if shouldRoundUp(a, nd) {
		a.RoundUp(nd)
	} else {
		a.RoundDown(nd)
	}
}

// 将 a 向下舍入（截断）到 nd 位（或更少位）。
func (a *decimal) RoundDown(nd int) {
	if nd < 0 || nd >= a.nd {
		return
	}
	a.nd = nd
	trim(a)
}

// 将 a 向上进位到 nd 位（或更少位）。
func (a *decimal) RoundUp(nd int) {
	if nd < 0 || nd >= a.nd {
		return
	}

	// 向上进位
	for i := nd - 1; i >= 0; i-- {
		c := a.d[i]
		if c < '9' { // 该位之后即可停止进位
			a.d[i]++
			a.nd = i + 1
			return
		}
	}

	// 数字全部为 9。
	// 改为单个 1，并相应调整小数点位置。
	a.d[0] = '1'
	a.nd = 1
	a.dp++
}

// 提取整数部分，并按需进行舍入。
// 不保证不会发生溢出。
func (a *decimal) RoundedInteger() uint64 {
	if a.dp > 20 {
		return 0xFFFFFFFFFFFFFFFF
	}
	var i int
	n := uint64(0)
	for i = 0; i < a.dp && i < a.nd; i++ {
		n = n*10 + uint64(a.d[i]-'0')
	}
	for ; i < a.dp; i++ {
		n *= 10
	}
	if shouldRoundUp(a, a.dp) {
		n++
	}
	return n
}
